// Generates src/lib/data/state-ui.ts from the research JSON files.
//
//   node scripts/seo/build-state-ui.mjs <amounts.json> <rules.json> <verifiedDate>
//
// amounts.json and rules.json are keyed by state code; every field is
// { value, source, asOf, note? }. Missing files or fields become nulls, which
// the pages render as "Check with <agency>". Never hand-fill a value here
// without an official source.
import fs from 'node:fs'

const [amountsPath, rulesPath, verified = new Date().toISOString().slice(0, 10)] = process.argv.slice(2)
const read = (p) => (p && fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : {})
const amounts = read(amountsPath)
const rules = read(rulesPath)

const CODES = ['AL','AK','AZ','AR','CA','CO','CT','DE','DC','FL','GA','HI','ID','IL','IN','IA','KS','KY','LA','ME','MD','MA','MI','MN','MS','MO','MT','NE','NV','NH','NJ','NM','NY','NC','ND','OH','OK','OR','PA','RI','SC','SD','TN','TX','UT','VT','VA','WA','WV','WI','WY']

// "accessed 2026-10-06" → "2026-10-06"; "url1 ; url2" → "url1".
const date = (d) => (d ? String(d).match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? null : null)
const url = (u) => (u ? String(u).split(/\s+;\s+|\s+/)[0] : null)
// "DOL Table 5-18 (2023 Comparison): all benefits are denied…" → "All benefits are denied…"
const plain = (t) => {
  if (!t) return null
  const s = String(t).replace(/^DOL Table [\d-]+ \([^)]*\):\s*/, '')
  return s.charAt(0).toUpperCase() + s.slice(1)
}

const fact = (f, kind) => {
  if (!f || typeof f !== 'object') return { value: null, source: null, asOf: null }
  let value = f.value ?? null
  if (value != null && kind === 'number') value = typeof value === 'number' ? value : Number(String(value).replace(/[$,]/g, ''))
  if (value != null && kind === 'number' && !Number.isFinite(value)) value = null
  if (value != null && kind === 'boolean' && typeof value !== 'boolean') value = null
  const out = { value, source: url(f.source), asOf: date(f.asOf) }
  const note = f.note ?? (value == null ? f.reason : null)
  if (note) out.note = note
  return out
}
const textFact = (f) => {
  if (!f) return { value: null, source: null, asOf: null, treatment: null }
  const value = plain(f.text ?? f.value)
  const out = { value, source: url(f.source), asOf: date(f.asOf), treatment: f.treatment ?? null }
  const note = f.note ?? (value == null ? f.reason : null)
  if (note) out.note = note
  return out
}

const data = {}
for (const code of CODES) {
  const a = amounts[code] ?? {}
  const r = rules[code] ?? {}
  const eb = a.extendedBenefitsStatus ?? a.extendedBenefits
  data[code] = {
    code,
    agencyName: fact(a.agencyName, 'string'),
    fileUrl: fact(a.fileUrl, 'string'),
    maxWeeklyBenefit: fact(a.maxWeeklyBenefit, 'number'),
    minWeeklyBenefit: fact(a.minWeeklyBenefit, 'number'),
    maxWeeks: fact(a.maxWeeks, 'number'),
    durationVaries: fact(a.durationVariesWithUnemploymentRate ?? a.durationVaries, 'boolean'),
    // Reader-facing: drop citations to DOL tables, which the source link covers.
    durationNote: ((a.durationNote && typeof a.durationNote === 'object' ? a.durationNote.value : a.durationNote) ?? '')
      .replace(/\s*\((?:DOL|per DOL)[^)]*\)/g, '').replace(/[.;]\s*DOL .*$/, '').trim() || null,
    waitingWeek: fact(a.waitingWeek, 'boolean'),
    severance: textFact(r.severance),
    payInLieuOfNotice: textFact(r.payInLieuOfNotice),
    workSearch: textFact(r.workSearch),
    extendedBenefits: fact(eb, 'string'),
    // Rules notes are research notes about the DOL table, not reader-facing.
    notes: a.notes || null,
  }
  delete data[code].workSearch.treatment
}

const body = `// GENERATED by scripts/seo/build-state-ui.mjs from official sources — do not hand-edit values.
// Every fact carries its source URL and as-of date. null means official sources
// disagreed or the value could not be confirmed; pages then say "Check with <agency>".
// Re-verify yearly: docs/STATE_UI_REVERIFICATION.md.

import type { StateUI } from './state-ui-types'

/** The date these facts were last checked against their sources. */
export const UI_LAST_VERIFIED = '${verified}'

export const STATE_UI: Record<string, StateUI> = ${JSON.stringify(data, null, 2)}
`
fs.writeFileSync('src/lib/data/state-ui.ts', body)
const filled = (k) => CODES.filter((c) => data[c][k].value != null).length
