// Writes docs/PERSONALIZATION_SPINE.md from src/lib/personalization/spine.ts,
// so the document can never drift from the questions we really ask.
//   npm run docs:spine
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DRIVE_LABELS, GROUP_LABELS, SIGNALS, spineFor, type Drive, type Group } from '../../src/lib/personalization/spine'
import { JOURNEYS, STAGES } from '../../src/lib/journey/journey'

const lines: string[] = []
lines.push('# Personalization spine', '')
lines.push('Generated by `npm run docs:spine` from `src/lib/personalization/spine.ts`. Do not edit by hand.', '')
lines.push('Personalization is the foundation for every journey and stage. Each question below is asked because its answer drives something we do: the weekly plan, learning and development, networking, the opportunities we show, the report or the coaching. Nothing is asked that does not drive something, and a test checks that every file named as reading an answer really reads it.', '')

lines.push('## Every question, what it drives and what it can open', '')
for (const group of Object.keys(GROUP_LABELS) as Group[]) {
  const signals = SIGNALS.filter((s) => s.group === group)
  if (signals.length === 0) continue
  lines.push(`### ${GROUP_LABELS[group]}`, '')
  lines.push('| Question | Stored in | What it drives | Opportunity it can open |', '|---|---|---|---|')
  for (const s of signals) {
    const drives = (Object.keys(s.drives) as Drive[]).map((d) => `**${DRIVE_LABELS[d]}:** ${s.drives[d]}`).join('<br>')
    lines.push(`| ${s.question} | \`${s.field}\` | ${drives} | ${s.opportunity} |`)
  }
  lines.push('')
}

lines.push('## What each journey is asked, by stage', '')
lines.push('Only questions that apply are asked. Culture details are asked only when someone says culture matters to them, so this lists the most they can be asked.', '')
for (const j of JOURNEYS) {
  lines.push(`### ${j.label}`, '', '| Stage | Questions |', '|---|---|')
  for (const st of STAGES) {
    const qs = spineFor(j.key, st.key, { cultureFit: { importance: 'important' } }).map((s) => s.question)
    lines.push(`| ${st.label} | ${qs.length ? qs.join('; ') : 'None'} |`)
  }
  lines.push('')
}

lines.push('## Collected outside the spine', '')
lines.push('Optional answers that drive something but are not asked as a spine question: `aiJobLossReason` (adds an AI outlook step to the plan), `travelWillingness` (job matching) and `biggestBarriers` (the report and rewrite actions).', '')

writeFileSync(join(__dirname, '../../docs/PERSONALIZATION_SPINE.md'), lines.join('\n'))
console.log('Wrote docs/PERSONALIZATION_SPINE.md')
