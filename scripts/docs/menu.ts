// Writes docs/CANDIDATE_MENU.md from the menu rules (src/lib/journey/menu.ts)
// and the six places (src/lib/nav/places.ts), so the document can never drift
// from the product.
//   npm run docs:menu
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { statusUnlock, type MenuMode } from '../../src/lib/journey/menu'
import { PLACES, tabSituation } from '../../src/lib/nav/places'

const MODES: { mode: MenuMode; name: string; who: string }[] = [
  { mode: 'EXPLORING', name: 'Exploring', who: 'Thinking about a move or planning ahead; not applying yet.' },
  { mode: 'PREPARING', name: 'Preparing', who: 'Getting ready to apply: résumé, proof, targets.' },
  { mode: 'ACTIVE', name: 'Active', who: 'Applying, interviewing or holding an offer. Also members with no stage yet.' },
  { mode: 'STAYING', name: 'Managing your career', who: 'Growing in a job, not looking right now, or going for a promotion before applying elsewhere.' },
  { mode: 'LANDED', name: 'Landed', who: 'Started a new job, first 90 days. Moves to Managing your career after 90 days.' },
  { mode: 'PORTFOLIO', name: 'Portfolio', who: 'Happy with fractional work: running a set of clients.' },
  { mode: 'LEAVE', name: 'On leave', who: 'Taking time off with a return date (family leave, sabbatical).' },
]

const lines: string[] = []
lines.push('# Candidate menu by situation', '')
lines.push('Generated by `npm run docs:menu` from `src/lib/journey/menu.ts` and `src/lib/nav/places.ts`. Do not edit by hand.', '')
lines.push('The dashboard has six places (Home, Jobs, Network, Learn, Personalize, Help), each with a tab row on every page.')
lines.push('The member\'s journey and stage decide which tabs are shown, locked or hidden. The rules are in `src/lib/journey/menu.ts` (tested in `src/test/menu.test.ts` and `src/test/place-tabs-situation.test.ts`).', '')

lines.push('## Show, lock, or hide', '')
lines.push('- **Show**: the tool helps in this situation.')
lines.push('- **Locked**: the tool turns on when the member\'s situation changes. The tab stays, muted, and a "Turn on more tools" box under the tab row says why it is off and updates the status in one click (the same change as "Has anything changed?"). This is how people learn why they should keep their status current.')
lines.push('- **Hidden**: the tool will not matter in this situation or the next one.', '')
lines.push('Locks for something the member can go and do (connect Gmail, take the Skills Assessment) are separate and keep their own reason. A tab with no situation rule always shows.', '')
lines.push('There is no "on a break" state for someone in the workforce: someone who is not looking is managing their career, with a plan, a menu and emails of their own. Time off with a return date is its own situation (On leave).', '')

lines.push('## The situations', '', '| Situation | Who is here |', '|---|---|')
for (const m of MODES) lines.push(`| ${m.name} | ${m.who} |`)
lines.push('')

lines.push('## Every tab, by situation', '')
lines.push('S = shown, L = locked until the status changes, blank = hidden. Tabs with no rule (always shown) are marked "all".', '')
lines.push(`| Place | Tab | ${MODES.map((m) => m.name).join(' | ')} |`, `|---|---|${MODES.map(() => '---').join('|')}|`)
for (const place of PLACES) {
  for (const tab of place.tabs) {
    const flags = [tab.employedOnly ? 'employed only' : '', tab.earlyCareerOnly ? 'early career only' : ''].filter(Boolean)
    const label = flags.length ? `${tab.label} (${flags.join(', ')})` : tab.label
    const cells = tab.menuKeys?.length
      ? MODES.map((m) => ({ show: 'S', locked: 'L', hide: '' })[tabSituation(tab, m.mode)])
      : MODES.map(() => 'all')
    lines.push(`| ${place.label} | ${label} | ${cells.join(' | ')} |`)
  }
}
lines.push('')

lines.push('## Why a tool is off, and how to turn it on', '')
for (const m of MODES) {
  const u = statusUnlock(m.mode)
  if (!u) continue
  lines.push(`**${m.name}.** ${u.why}`, '')
  for (const a of u.answers) lines.push(`- "${a.label}": ${a.because}`)
  lines.push('')
}

writeFileSync(join(__dirname, '../../docs/CANDIDATE_MENU.md'), lines.join('\n'))
console.log('Wrote docs/CANDIDATE_MENU.md')
