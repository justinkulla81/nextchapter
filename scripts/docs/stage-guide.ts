// Writes docs/CANDIDATE_STAGES.md from src/lib/journey/stage-guide.ts and the
// menu rules, so the document can never drift from the product.
//   npm run docs:stages
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { MENU_LABELS } from '../../src/lib/journey/menu'
import { STAGE_GUIDE, STAGE_ORDER, menuFor, stageDescription, stageName } from '../../src/lib/journey/stage-guide'

const lines: string[] = []
lines.push('# Candidate stages: activities, features, menu and marketing text', '')
lines.push('Generated by `npm run docs:stages` from `src/lib/journey/stage-guide.ts` and the menu rules in `src/lib/journey/menu.ts`. Do not edit by hand.', '')
lines.push('A stage is how close someone is to applying. There is no "on a break": someone who is not looking is *managing their career*.')
lines.push('How hard someone is looking (actively or casually) is a separate setting that changes the pace within a stage; see each stage\'s note.', '')

for (const stage of STAGE_ORDER) {
  const g = STAGE_GUIDE[stage]
  const menu = menuFor(stage)
  lines.push(`## ${stageName(stage)}`, '')
  lines.push(`**What it is for:** ${stageDescription(stage)}`, '')
  lines.push(`**Who is here:** ${g.who}`, '')
  lines.push('**Marketing text**', '', `> **${g.marketing.headline}** ${g.marketing.body}`, '')
  lines.push('**Key activities and the feature for each**', '', '| Activity | Feature (menu) |', '|---|---|')
  for (const a of g.activities) lines.push(`| ${a.activity} | ${MENU_LABELS[a.feature]} |`)
  lines.push('')
  lines.push(`**On the menu:** ${menu.shown.join(', ')}.`, '')
  lines.push(menu.locked.length > 0 ? `**Visible but locked (turn on by updating your status):** ${menu.locked.join(', ')}.` : '**Locked:** nothing.', '')
  lines.push(`**Emails and prompts:** ${g.emails.join('; ')}.`, '')
  if (g.casualNote) lines.push(`**If looking casually:** ${g.casualNote}`, '')
}

writeFileSync(join(__dirname, '../../docs/CANDIDATE_STAGES.md'), lines.join('\n'))
console.log('Wrote docs/CANDIDATE_STAGES.md')
