#!/usr/bin/env python3
"""Build prisma/manual/<date>-area-housing.sql from the Census Bureau's ACS 5-year table-based summary files.

  python3 -I scripts/housing/import_census_housing.py DIR OUT.sql

DIR holds acsdt5y2024-b25064.dat (median gross rent), acsdt5y2024-b25077.dat (median home value) and Geos20245YR.txt
(from https://www2.census.gov/programs-surveys/acs/summary_file/2024/table-based-SF/). One row per metropolitan or
micropolitan area (areaType METRO, areaCode = CBSA code, the same code the OEWS pay data uses), per state, and the
United States. Estimates the Bureau did not publish (blank, '-' or a negative sentinel) are left null.
"""
import sys, pathlib

YEAR = 2024
LEVELS = {'010': 'NATIONAL', '040': 'STATE', '310': 'METRO'}

def table(path, col):
    out = {}
    with open(path, encoding='utf-8') as f:
        head = f.readline().rstrip('\n').split('|')
        i = head.index(col)
        for line in f:
            p = line.rstrip('\n').split('|')
            out[p[0]] = p[i]
    return out

def num(v):
    try:
        n = int(float(v))
    except (TypeError, ValueError):
        return None
    return n if n > 0 else None  # the Bureau uses negative sentinels for "not available"

def main(d, dest):
    d = pathlib.Path(d)
    rent = table(d / 'acsdt5y2024-b25064.dat', 'B25064_E001')
    home = table(d / 'acsdt5y2024-b25077.dat', 'B25077_E001')
    rows = []
    with open(d / 'Geos20245YR.txt', encoding='utf-8', errors='replace') as f:
        head = f.readline().rstrip('\n').split('|')
        ix = {k: head.index(k) for k in ('SUMLEVEL', 'COMPONENT', 'STATE', 'CBSA', 'GEO_ID', 'NAME')}
        for line in f:
            p = line.rstrip('\n').split('|')
            if len(p) < len(head) or p[ix['SUMLEVEL']] not in LEVELS or p[ix['COMPONENT']] != '00':
                continue
            kind, gid = LEVELS[p[ix['SUMLEVEL']]], p[ix['GEO_ID']]
            code = {'NATIONAL': 'US', 'STATE': p[ix['STATE']], 'METRO': p[ix['CBSA']]}[kind]
            r, h = num(rent.get(gid)), num(home.get(gid))
            if not code or (r is None and h is None):
                continue
            rows.append((kind, code, p[ix['NAME']], r, h))
    rows.sort()
    q = lambda s: "'" + s.replace("'", "''") + "'"
    v = lambda n: 'null' if n is None else str(n)
    with open(dest, 'w', encoding='utf-8') as o:
        o.write(f'-- Census ACS {YEAR - 4}-{YEAR} 5-year: median gross rent (B25064) and median home value (B25077). Generated by scripts/housing/import_census_housing.py.\n')
        o.write('begin;\ndelete from "AreaHousing" where "source" = ' + q(f'acs5-{YEAR}') + ';\n')
        for k in range(0, len(rows), 200):
            o.write('insert into "AreaHousing" ("areaType","areaCode","name","medianRent","medianHomeValue","source") values\n')
            o.write(',\n'.join(f"({q(a)},{q(b)},{q(c)},{v(r)},{v(h)},{q(f'acs5-{YEAR}')})" for a, b, c, r, h in rows[k:k + 200]))
            o.write(';\n')
        o.write('commit;\n')
    print(len(rows), 'areas')
    by = {}
    for a, *_ in rows: by[a] = by.get(a, 0) + 1
    print(by)

main(*sys.argv[1:3])
