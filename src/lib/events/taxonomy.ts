export const INDUSTRIES = Object.keys(TAXONOMY)
export const SEGMENTS: string[] = [...new Set(INDUSTRIES.flatMap((i) => Object.keys(TAXONOMY[i])))]
export const segmentsOf = (industry: string): string[] => Object.keys(TAXONOMY[industry] ?? {})
export const rolesOf = (industry: string, segment: string): string[] => TAXONOMY[industry]?.[segment] ?? []
export const cellCount = INDUSTRIES.reduce((n, i) => n + Object.keys(TAXONOMY[i]).length, 0)

/** Segments belonging to the given industries (all of them when the list is empty). */
export function segmentsForIndustries(industries: string[]): string[] {
  return [...new Set((industries.length ? industries : INDUSTRIES).flatMap(segmentsOf))]
}
